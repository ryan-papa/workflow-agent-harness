def split_frontmatter(path: Path) -> tuple[dict[str, str], str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{path} missing YAML frontmatter")

    end = text.find("\n---\n", 4)
    if end == -1:
        raise ValueError(f"{path} missing closing YAML frontmatter")

    raw_meta = text[4:end].splitlines()
    body = text[end + len("\n---\n") :]
    meta: dict[str, str] = {}

    for line in raw_meta:
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        value = value.strip()
        if (value.startswith("'") and value.endswith("'")) or (
            value.startswith('"') and value.endswith('"')
        ):
            value = value[1:-1]
        meta[key.strip()] = value

    return meta, body


def adapt_body(body: str, cfg: TargetConfig) -> str:
    adapted = body
    for before, after in cfg.replacements:
        adapted = adapted.replace(before, after)

    # .<runtime>/skills/<name>/SKILL.md 기준으로 docs/skills/ 상대 링크 재작성
    adapted = re.sub(r"\]\(\./", "](", adapted)
    adapted = re.sub(r"\]\(\.\./", "](../../../docs/", adapted)
    adapted = re.sub(r"\]\(([\w-]+\.md)", r"](../../../docs/skills/\1", adapted)
    return adapted


def render_skill(source: Path, cfg: TargetConfig, root: Path = ROOT) -> str:
    name = source.stem
    meta, body = split_frontmatter(source)
    original_description = meta.get("description")
    if not original_description:
        raise ValueError(f"{source} missing description")

    suffix = cfg.description_suffix.format(name=name)
    description = f"{original_description.rstrip('.')}.{suffix}"
    rel_source = source.relative_to(root)

    return (
        "---\n"
        f"name: {name}\n"
        f"description: {json.dumps(description, ensure_ascii=False)}\n"
        "---\n\n"
        + cfg.generated_note.format(rel_source=rel_source)
        + cfg.adapter_notes
        + adapt_body(body, cfg)
    )


def render_all_skills(
    cfg: TargetConfig,
    source_dir: Path = SOURCE_DIR,
    root: Path = ROOT,
) -> dict[str, str]:
    """Validate and render every rp-*.md in memory before mutating disk."""
    rendered: dict[str, str] = {}
    for source in sorted(source_dir.glob("rp-*.md")):
        rendered[source.stem] = render_skill(source, cfg, root=root)
    return rendered


@contextlib.contextmanager
def _dest_lock(dest_dir: Path) -> Iterator[None]:
    """Serialize concurrent syncs targeting the same directory without dirtying the repo."""
    digest = hashlib.sha256(str(dest_dir.resolve()).encode("utf-8")).hexdigest()[:16]
    lock_path = Path(tempfile.gettempdir()) / f"harness-sync-skills-{digest}.lock"
    with lock_path.open("w", encoding="utf-8") as fh:
        fcntl.flock(fh.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(fh.fileno(), fcntl.LOCK_UN)


def _atomic_write_text(path: Path, content: str) -> None:
    fd, tmp_name = tempfile.mkstemp(prefix=".skill-", suffix=".tmp", dir=str(path.parent))
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(content)
        os.chmod(tmp_path, 0o644)
        os.replace(tmp_path, path)
    except Exception:
        with contextlib.suppress(OSError):
            tmp_path.unlink()
        raise


def build_tree(
    target: Path,
    cfg: TargetConfig,
    source_dir: Path = SOURCE_DIR,
    root: Path = ROOT,
) -> list[str]:
    rendered = render_all_skills(cfg, source_dir=source_dir, root=root)
    target.mkdir(parents=True, exist_ok=True)

    for name, content in rendered.items():
        skill_dir = target / name
        skill_dir.mkdir(parents=True, exist_ok=True)
        _atomic_write_text(skill_dir / "SKILL.md", content)

    return list(rendered.keys())


def sync_target(cfg: TargetConfig, source_dir: Path = SOURCE_DIR, root: Path = ROOT) -> Path:
    dest_dir = root / cfg.dest_rel
    dest_dir.mkdir(parents=True, exist_ok=True)

    with _dest_lock(dest_dir):
        # Render and validate all sources under lock before mutating existing skills.
        rendered = render_all_skills(cfg, source_dir=source_dir, root=root)
        for name, content in rendered.items():
            skill_dir = dest_dir / name
            skill_dir.mkdir(parents=True, exist_ok=True)
            _atomic_write_text(skill_dir / "SKILL.md", content)
        for child in list(dest_dir.iterdir()):
            if child.is_dir() and child.name.startswith("rp-") and child.name not in rendered:
                shutil.rmtree(child)
    return dest_dir


def sync_claude_links(
    source_dir: Path = SOURCE_DIR, commands_dir: Path = CLAUDE_COMMANDS_DIR
) -> list[str]:
    commands_dir.mkdir(parents=True, exist_ok=True)
    created: list[str] = []
    for source in sorted(source_dir.glob("rp-*.md")):
        link = commands_dir / source.name
        if not link.exists() and not link.is_symlink():
            link.symlink_to(Path("..") / ".." / "docs" / "skills" / source.name)
            created.append(source.name)
    return created


def install_user_target(
    cfg: TargetConfig,
    source_dir: Path = SOURCE_DIR,
    dest_dir: Path | None = None,
    user_skills_dir: Path | None = None,
) -> Path:
    src_dest = dest_dir or cfg.dest_dir
    user_dir = user_skills_dir or cfg.user_dir_fn()
    user_dir.mkdir(parents=True, exist_ok=True)
    names = [source.stem for source in sorted(source_dir.glob("rp-*.md"))]

    for name in names:
        target = src_dest / name
        link = user_dir / name
        if link.is_symlink() or not link.exists():
            if link.exists() or link.is_symlink():
                link.unlink()
            link.symlink_to(target, target_is_directory=True)
            continue
        print(f"skip existing non-symlink: {link}", file=sys.stderr)

    return user_dir


def check_target(
    cfg: TargetConfig,
    source_dir: Path = SOURCE_DIR,
    dest_dir: Path | None = None,
    root: Path = ROOT,
) -> int:
    actual_dest = dest_dir or (root / cfg.dest_rel)
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dest = Path(tmp) / "skills"
        names = build_tree(tmp_dest, cfg, source_dir=source_dir, root=root)

        missing: list[str] = []
        changed: list[str] = []

        for name in names:
            expected = tmp_dest / name / "SKILL.md"
            actual = actual_dest / name / "SKILL.md"
            if not actual.exists():
                missing.append(name)
                continue
            if actual.read_text(encoding="utf-8") != expected.read_text(encoding="utf-8"):
                changed.append(name)

        extra = sorted(
            child.name
            for child in actual_dest.glob("rp-*")
            if child.is_dir() and child.name not in names
        )

    if missing or changed or extra:
        if missing:
            print(f"[{cfg.name}] missing:", ", ".join(missing), file=sys.stderr)
        if changed:
            print(f"[{cfg.name}] out-of-date:", ", ".join(changed), file=sys.stderr)
        if extra:
            print(f"[{cfg.name}] extra:", ", ".join(extra), file=sys.stderr)
        return 1

    print(f"{cfg.label} skills in sync: {len(names)}")
    return 0


def resolve_targets(choice: str) -> list[TargetConfig]:
    if choice == "all":
        return [TARGETS["codex"], TARGETS["antigravity"]]
    return [TARGETS[choice]]


def self_test() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        src_dir = root / "docs" / "skills"
        src_dir.mkdir(parents=True)
        skill = src_dir / "rp-demo.md"
        skill.write_text(
            "---\n"
            "description: '데모 스킬'\n"
            "---\n\n"
            "# rp-demo\n\n"
            "Agent 툴의 서브에이전트와 Doc Agent 참조: [다른스킬](./rp-other.md) · [상위](../harness-prd.md) · [직접](rp-peer.md)\n",
            encoding="utf-8",
        )

        # 1. Sync & check for both targets
        for cfg in resolve_targets("all"):
            dest = sync_target(cfg, source_dir=src_dir, root=root)
            rendered = (dest / "rp-demo" / "SKILL.md").read_text(encoding="utf-8")
            assert "../../../docs/harness-prd.md" in rendered
            assert "../../../docs/skills/rp-other.md" in rendered
            assert "../../../docs/skills/rp-peer.md" in rendered
            assert "python3 scripts/sync-skills.py" in rendered
            assert check_target(cfg, source_dir=src_dir, dest_dir=dest, root=root) == 0

        codex_text = (root / ".codex" / "skills" / "rp-demo" / "SKILL.md").read_text(encoding="utf-8")
        agy_text = (root / ".agents" / "skills" / "rp-demo" / "SKILL.md").read_text(encoding="utf-8")
        assert "`spawn_agent` 서브에이전트" in codex_text
        assert "`invoke_subagent` 서브에이전트" in agy_text
        assert "문서 작성자" in codex_text and "문서 작성자" in agy_text

        # 2. Drift detection: changed, extra, missing
        agy_skill = root / ".agents" / "skills" / "rp-demo" / "SKILL.md"
        agy_skill.write_text("tampered\n", encoding="utf-8")
        assert check_target(TARGETS["antigravity"], source_dir=src_dir, root=root) == 1
        sync_target(TARGETS["antigravity"], source_dir=src_dir, root=root)
        (root / ".agents" / "skills" / "rp-extra").mkdir()
        assert check_target(TARGETS["antigravity"], source_dir=src_dir, root=root) == 1
        sync_target(TARGETS["antigravity"], source_dir=src_dir, root=root)
        assert not (root / ".agents" / "skills" / "rp-extra").exists()
        agy_skill.unlink()
        assert check_target(TARGETS["antigravity"], source_dir=src_dir, root=root) == 1
        sync_target(TARGETS["antigravity"], source_dir=src_dir, root=root)

        # 3. install_user: symlink + non-symlink skip
        user_dir = root / "user-skills"
        user_dir.mkdir()
        install_user_target(
            TARGETS["antigravity"],
            source_dir=src_dir,
            dest_dir=root / ".agents" / "skills",
            user_skills_dir=user_dir,
        )
        assert (user_dir / "rp-demo").is_symlink()

        user_dir_conflict = root / "user-conflict"
        (user_dir_conflict / "rp-demo").mkdir(parents=True)
        install_user_target(
            TARGETS["antigravity"],
            source_dir=src_dir,
            dest_dir=root / ".agents" / "skills",
            user_skills_dir=user_dir_conflict,
        )
        assert not (user_dir_conflict / "rp-demo").is_symlink()

        # 4. Claude commands symlink helper
        cmd_dir = root / ".claude" / "commands"
        created = sync_claude_links(source_dir=src_dir, commands_dir=cmd_dir)
        assert created == ["rp-demo.md"]
        assert (cmd_dir / "rp-demo.md").is_symlink()

        # 5. Missing frontmatter fails fast WITHOUT destroying existing synced skills
        bad = src_dir / "rp-bad.md"
        bad.write_text("# no frontmatter\n", encoding="utf-8")
        for cfg in resolve_targets("all"):
            try:
                sync_target(cfg, source_dir=src_dir, root=root)
                raise AssertionError("missing frontmatter should fail")
            except ValueError:
                pass
        assert (root / ".codex" / "skills" / "rp-demo" / "SKILL.md").read_text(encoding="utf-8") == codex_text
        assert (root / ".agents" / "skills" / "rp-demo" / "SKILL.md").read_text(encoding="utf-8") == agy_text
    print("self-test OK")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--target",
        choices=["all", "codex", "antigravity"],
        default="all",
        help="target runtime(s) to sync or check (default: all)",
    )
    parser.add_argument("--check", action="store_true", help="verify generated skills are current")
    parser.add_argument(
        "--install-user",
        action="store_true",
        help="symlink generated rp-* skills into each target's user skills directory",
    )
    parser.add_argument(
        "--sync-claude-links",
        action="store_true",
        help="also ensure missing .claude/commands/rp-*.md symlinks exist",
    )
    parser.add_argument("--self-test", action="store_true", help="run built-in fixture checks")
    args = parser.parse_args(argv)

    if args.self_test:
        self_test()
        return 0

    targets = resolve_targets(args.target)
    if args.check:
        rc = 0
        for cfg in targets:
            if check_target(cfg) != 0:
                rc = 1
        return rc

    if args.sync_claude_links:
        for name in sync_claude_links():
            print(f"Created Claude command symlink: .claude/commands/{name}")

    for cfg in targets:
        dest = sync_target(cfg)
        print(f"Generated {cfg.label} skills in {dest.relative_to(ROOT)}")
        if args.install_user:
            user_dir = install_user_target(cfg, dest_dir=dest)
            print(f"Installed {cfg.label} user skill links in {user_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
