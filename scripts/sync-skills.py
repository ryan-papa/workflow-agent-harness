@dataclass(frozen=True)
class TargetConfig:
    name: str
    label: str
    dest_rel: Path
    user_dir_fn: Callable[[], Path]
    description_suffix: str
    generated_note: str
    adapter_notes: str
    replacements: tuple[tuple[str, str], ...]

    @property
    def dest_dir(self) -> Path:
        return ROOT / self.dest_rel


